/// The enrichment fallback's dictionary (`docs/reference/transactions.md`, **Merchants**):
/// normalized merchant names, each with the prefixes of a bank's raw transaction name that
/// mean it and, where the brand has a well-known one, its color. No logos are bundled
/// (`PLAN.md` §12: brand logos are trademarks; a letter avatar is honest and license-free).
/// Pure Dart.
///
/// A key is matched after `normalizeMerchantText` (lower case, apostrophes dropped, every
/// other run of punctuation a space), as whole words at the start of the name, so
/// `NETFLIX.COM` matches `netflix` and `APPLEBEES` does not match `apple`. The longest key
/// wins. A [MerchantEntry.color] is opaque ARGB; null means the palette color hashed on the
/// name.
library;

/// One merchant: its [name] as shown, the raw-name prefixes ([keys]) that mean it, and its
/// brand [color] when it has a well-known one.
final class MerchantEntry {
  const MerchantEntry(this.name, this.keys, [this.color]);

  final String name;
  final List<String> keys;
  final int? color;
}

