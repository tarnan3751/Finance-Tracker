/// The enrichment fallback's dictionary (`docs/reference/transactions.md`, **Merchants**):
/// normalized merchant names, each with the prefixes of a bank's raw transaction name that
/// mean it. No logos are bundled (`PLAN.md` §12: brand logos are trademarks; a letter
/// avatar is honest and license-free). Pure Dart.
///
/// A key is matched after `normalizeMerchantText` (lower case, apostrophes dropped, every
/// other run of punctuation a space), as whole words at the start of the name, so
/// `NETFLIX.COM` matches `netflix` and `APPLEBEES` does not match `apple`. The longest key
/// wins.
library;

/// One merchant: its [name] as shown and the raw-name prefixes ([keys]) that mean it.
final class MerchantEntry {
  const MerchantEntry(this.name, this.keys);

  final String name;
  final List<String> keys;
}

