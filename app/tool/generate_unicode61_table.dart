// Writes lib/features/transactions/domain/unicode61_table.dart: how the bundled SQLite's
// FTS5 tokenizer `unicode61 remove_diacritics 2` treats every code point, read from the
// tokenizer itself, for the in-memory search (search_text.dart). Run it from app/ after
// the sqlite3 package's SQLite changes:
//
//   dart run tool/generate_unicode61_table.dart
//
// The gate's search_text_test.dart compares the table with the tokenizer and fails when
// they differ. Each code point c (surrogates excepted) is indexed in `q<c>z`: two tokens
// mean c separates tokens; one token `q<f>z` that c folds to f, `qz` that it is dropped.
import 'dart:io';

import 'package:sqlite3/sqlite3.dart';

const String _output = 'lib/features/transactions/domain/unicode61_table.dart';

void main() {
  final Database db = sqlite3.openInMemory();
  final String version =
      db.select('SELECT sqlite_version() AS v').single['v'] as String;
  db.execute(
    "CREATE VIRTUAL TABLE f USING fts5(x, tokenize = 'unicode61 remove_diacritics 2')",
  );
  db.execute("CREATE VIRTUAL TABLE v USING fts5vocab(f, 'instance')");
  db.execute('BEGIN');
  final PreparedStatement insert = db.prepare(
    'INSERT INTO f(rowid, x) VALUES (?, ?)',
  );
  for (int cp = 1; cp <= 0x10FFFF; cp++) {
    if (cp >= 0xD800 && cp <= 0xDFFF) continue;
    insert.execute([cp, 'q${String.fromCharCode(cp)}z']);
  }
  insert.close();
  db.execute('COMMIT');
  final Map<int, List<String>> terms = {};
  for (final Row row in db.select(
    'SELECT doc, term FROM v ORDER BY doc, "offset"',
  )) {
    (terms[row['doc'] as int] ??= []).add(row['term'] as String);
  }
  db.close();

  final List<int> separators = [];
  final Map<int, int> folds = {};
  int? rangeStart;
  for (int cp = 0; cp <= 0x110000; cp++) {
    final bool surrogate = cp >= 0xD800 && cp <= 0xDFFF;
    // NUL is never sent to SQLite inside text; it is taken as a separator.
    final List<String> t = cp == 0
        ? const ['q', 'z']
        : cp > 0x10FFFF || surrogate
        ? const []
        : terms[cp]!;
    final bool separates = t.length == 2;
    if (separates) {
      rangeStart ??= cp;
    } else if (!surrogate && rangeStart != null) {
      separators
        ..add(rangeStart)
        ..add(cp - 1);
      rangeStart = null;
    }
    if (t.length == 1) {
      final List<int> middle = t.single.runes.toList().sublist(
        1,
        t.single.runes.length - 1,
      );
      if (middle.isEmpty) {
        folds[cp] = 0;
      } else if (middle.length == 1) {
        if (middle.single != cp) folds[cp] = middle.single;
      } else {
        throw StateError('U+${cp.toRadixString(16)} folds to ${middle.length}');
      }
    }
  }

  String hex(int v) => '0x${v.toRadixString(16).toUpperCase()}';
  final StringBuffer out = StringBuffer()
    ..writeln(
      '// GENERATED by tool/generate_unicode61_table.dart from SQLite $version;',
    )
    ..writeln('// do not edit. Rerun the tool when the bundled SQLite changes.')
    ..writeln('library;')
    ..writeln()
    ..writeln(
      '/// The code points FTS5 `unicode61` treats as separators, as inclusive',
    )
    ..writeln('/// `[first, last]` pairs in ascending order.')
    ..writeln('const List<int> unicode61Separators = [');
  for (int i = 0; i < separators.length; i += 2) {
    out.writeln('  ${hex(separators[i])}, ${hex(separators[i + 1])},');
  }
  out
    ..writeln('];')
    ..writeln()
    ..writeln(
      '/// The token characters `unicode61 remove_diacritics 2` folds to another',
    )
    ..writeln(
      '/// code point (case and Latin diacritics), or drops (0: a combining mark).',
    )
    ..writeln('const Map<int, int> unicode61Folds = {');
  for (final MapEntry<int, int> e in folds.entries) {
    out.writeln('  ${hex(e.key)}: ${hex(e.value)},');
  }
  out.writeln('};');
  File(_output).writeAsStringSync(out.toString());
  Process.runSync('dart', ['format', _output]);
  stdout.writeln(
    'wrote $_output: ${separators.length ~/ 2} separator ranges, '
    '${folds.length} folds (SQLite $version)',
  );
}
