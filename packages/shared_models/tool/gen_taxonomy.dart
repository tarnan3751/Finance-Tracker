/// Generates `lib/src/taxonomy/plaid_taxonomy.dart` from `tool/plaid_taxonomy.csv`.
///
///     dart run tool/gen_taxonomy.dart        (in packages/shared_models)
///
/// The CSV is Plaid's published personal-finance category taxonomy, committed byte for
/// byte as downloaded from [sourceUrl] on [downloadDate]. It carries the version 2
/// taxonomy in its first three columns and the version 1 mapping in the last three; only
/// version 2 is generated. Its second row is a note, not a category, and is skipped.
/// When the CSV is downloaded again, update [downloadDate] and rerun this script;
/// `test/taxonomy_test.dart` fails while the generated file and the CSV disagree.
library;

import 'dart:io';

/// Where the CSV comes from.
const sourceUrl = 'https://plaid.com/documents/pfc-taxonomy-all.csv';

/// The day `tool/plaid_taxonomy.csv` was downloaded.
const downloadDate = '2026-10-24';

/// The CSV, relative to the package root.
const csvPath = 'tool/plaid_taxonomy.csv';

/// The generated file, relative to the package root.
const outputPath = 'lib/src/taxonomy/plaid_taxonomy.dart';

Future<void> main() async {
  final source = await formattedTaxonomy(File(csvPath).readAsStringSync());
  File(outputPath).writeAsStringSync(source);
  stdout.writeln('wrote $outputPath');
}

/// The generated Dart source for [csv], formatted by `dart format` as the gate expects.
/// Must run from the package root (it formats inside `.dart_tool/`).
Future<String> formattedTaxonomy(String csv) async {
  final scratch = Directory('.dart_tool/gen_taxonomy')
    ..createSync(recursive: true);
  final file = File('${scratch.path}/plaid_taxonomy.dart')
    ..writeAsStringSync(renderTaxonomy(csv));
  final result = await Process.run(Platform.resolvedExecutable, [
    'format',
    file.path,
  ]);
  if (result.exitCode != 0) {
    throw StateError('dart format failed: ${result.stderr}');
  }
  return file.readAsStringSync();
}

/// The generated Dart source for [csv], before formatting.
String renderTaxonomy(String csv) {
  final rows = parseCsv(csv);
  const header = ['PFCv2 Primary', 'PFCv2 Detailed', 'PFCv2 Description'];
  if (rows.isEmpty ||
      rows.first.length < 3 ||
      !_startsWith(rows.first, header)) {
    throw FormatException('Unexpected taxonomy header', rows.firstOrNull);
  }
  final code = RegExp(r'^[A-Z][A-Z_]*$');
  final entries = <List<String>>[];
  for (final row in rows.skip(1)) {
    if (row.length < 3 || row[1].isEmpty) continue; // the note row
    final [primary, detailed, description, ...] = row;
    if (!code.hasMatch(primary) || !code.hasMatch(detailed)) {
      throw FormatException('Unexpected taxonomy row', row);
    }
    entries.add([primary, detailed, description]);
  }
  final primaries = <String>{for (final entry in entries) entry[0]};

  final out = StringBuffer()
    ..writeln(
      '// GENERATED by tool/gen_taxonomy.dart from $csvPath; do not edit.',
    )
    ..writeln(
      '// Source: $sourceUrl (PFCv2 columns), downloaded $downloadDate.',
    )
    ..writeln('// Regenerate: dart run tool/gen_taxonomy.dart')
    ..writeln()
    ..writeln("/// Plaid's personal-finance category taxonomy, version 2.")
    ..writeln('///')
    ..writeln(
      '/// Reference data from Plaid\'s documentation, not a Plaid call.',
    )
    ..writeln('library;')
    ..writeln()
    ..writeln(
      "import 'package:shared_models/src/taxonomy/plaid_category.dart';",
    )
    ..writeln()
    ..writeln('/// Every detailed category, in the order Plaid publishes them.')
    ..writeln('const List<PlaidCategory> plaidCategories = [');
  for (final [primary, detailed, description] in entries) {
    out.writeln(
      '  PlaidCategory(primary: ${_literal(primary)}, '
      'detailed: ${_literal(detailed)}, '
      'description: ${_literal(description)},),',
    );
  }
  out
    ..writeln('];')
    ..writeln()
    ..writeln('/// The primary category codes.')
    ..writeln('const Set<String> plaidPrimaryCategories = {');
  for (final primary in primaries) {
    out.writeln('  ${_literal(primary)},');
  }
  out.writeln('};');
  return out.toString();
}

/// Parses RFC 4180 CSV: quoted fields may hold commas, doubled quotes and line breaks;
/// rows end with LF or CRLF.
List<List<String>> parseCsv(String text) {
  final rows = <List<String>>[];
  var row = <String>[];
  final field = StringBuffer();
  var quoted = false;
  for (var i = 0; i < text.length; i++) {
    final c = text[i];
    if (quoted) {
      if (c == '"') {
        if (i + 1 < text.length && text[i + 1] == '"') {
          field.write('"');
          i++;
        } else {
          quoted = false;
        }
      } else {
        field.write(c);
      }
    } else if (c == '"') {
      quoted = true;
    } else if (c == ',') {
      row.add(field.toString());
      field.clear();
    } else if (c == '\n' || c == '\r') {
      if (c == '\r' && i + 1 < text.length && text[i + 1] == '\n') i++;
      row.add(field.toString());
      field.clear();
      rows.add(row);
      row = <String>[];
    } else {
      field.write(c);
    }
  }
  if (field.isNotEmpty || row.isNotEmpty) {
    row.add(field.toString());
    rows.add(row);
  }
  return rows;
}

bool _startsWith(List<String> row, List<String> prefix) {
  for (var i = 0; i < prefix.length; i++) {
    if (row[i] != prefix[i]) return false;
  }
  return true;
}

String _literal(String value) {
  final escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$');
  return "'$escaped'";
}
